# AutomationKit - one-click start for the self-hosted n8n template pack.
# Requirement: Docker Desktop is installed and running.
# First run pulls about 1.5 GB of images.
#
# This script is intentionally plain ASCII and avoids fancy syntax so it
# works on Windows PowerShell 5.1 as well as PowerShell 7.

$ErrorActionPreference = 'Continue'
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
Set-Location $root

function Write-Step($m) { Write-Host "[ .. ] $m" -ForegroundColor Cyan }
function Write-Ok($m)   { Write-Host "[ ok ] $m" -ForegroundColor Green }
function Write-Bad($m)  { Write-Host "[fail] $m" -ForegroundColor Red }

# ---------------------------------------------------------------- 1. docker
Write-Step "checking docker"
docker info --format '{{.ServerVersion}}' 2>$null | Out-Null
if ($LASTEXITCODE -ne 0) {
    Write-Bad "docker is not running. Start Docker Desktop, then run this script again."
    exit 1
}
Write-Ok "docker is running"

# ---------------------------------------------------------------- 2. .env
$envPath = Join-Path $root '.env'
if (-not (Test-Path $envPath)) {
    Write-Step "creating .env with a generated encryption key"

    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()

    $keyBytes = New-Object byte[] 24
    $rng.GetBytes($keyBytes)
    $encKey = -join ($keyBytes | ForEach-Object { $_.ToString('x2') })

    $pwBytes = New-Object byte[] 16
    $rng.GetBytes($pwBytes)
    $pgPass = -join ($pwBytes | ForEach-Object { $_.ToString('x2') })

    $lines = @(
        '# generated by start.ps1 - keep this file private',
        'POSTGRES_USER=autokit',
        "POSTGRES_PASSWORD=$pgPass",
        'POSTGRES_DB=autokit',
        "N8N_ENCRYPTION_KEY=$encKey",
        'GENERIC_TIMEZONE=Asia/Shanghai'
    )
    Set-Content -Path $envPath -Value $lines -Encoding ASCII
    Write-Ok ".env created"
}
else {
    Write-Ok ".env already exists, keeping the current key"
}

# ---------------------------------------------------------------- 3. compose up
Write-Step "starting containers (first run downloads the images, be patient)"
docker compose up -d
if ($LASTEXITCODE -ne 0) {
    Write-Bad "docker compose up failed"
    exit 1
}

# ---------------------------------------------------------------- 4. wait healthy
Write-Step "waiting for n8n to report healthy (max 240s)"
$deadline = (Get-Date).AddSeconds(240)
$healthy = $false
while ((Get-Date) -lt $deadline) {
    $status = docker inspect --format '{{.State.Health.Status}}' ak-n8n 2>$null
    if ($status -eq 'healthy') {
        $healthy = $true
        break
    }
    Write-Host "." -NoNewline
    Start-Sleep -Seconds 5
}
Write-Host ""

if ($healthy) {
    Write-Ok "n8n is up"
}
else {
    Write-Bad "n8n did not become healthy in time. Check logs with: docker compose logs ak-n8n"
}

# ---------------------------------------------------------------- 5. summary
Write-Host ""
Write-Host "n8n editor : http://localhost:5678"
Write-Host "postgres   : localhost:5433   user=autokit  db=autokit"
Write-Host ""
Write-Host "import one template:"
Write-Host "  docker compose exec n8n n8n import:workflow --input=/data/templates/lead-routing/workflow.json"
Write-Host ""
Write-Host "stop:            docker compose down"
Write-Host "stop + wipe data: docker compose down -v"
Write-Host ""

if (-not $healthy) { exit 1 }
exit 0
